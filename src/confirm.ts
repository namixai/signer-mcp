// Согласие на трату — отдельная вещь, потому что ошибиться в ней дороже всего.
//
// 🔴 ТРИ СПОСОБА СКАЗАТЬ «ДА» ПО ОШИБКЕ, и все три встречались здесь:
//   1. любая клавиша считалась согласием — включая «no»;
//   2. EOF (закрытый терминал, перенаправленный ввод, запуск из скрипта) давал пустую
//      строку, а пустая строка означала Enter, то есть «да» без единого нажатия;
//   3. отсутствие терминала вовсе — тогда спрашивать некого, и молчание не согласие.
//
// Согласие требует, чтобы человек ДЕЙСТВИТЕЛЬНО нажал. Всё остальное — отказ.

export interface ConfirmResult {
  ok: boolean;
  reason?: "eof" | "declined" | "no_tty";
  answer?: string;
}

/**
 * @param read — читает из терминала, возвращает число прочитанных байт и буфер.
 *               Отдельным параметром, чтобы это можно было проверить тестом, а не
 *               доверять на слово: подтверждение платежа — не то место для доверия.
 */
export function interpretConfirmation(n: number, buf: Buffer): ConfirmResult {
  if (n <= 0) return { ok: false, reason: "eof" };
  const answer = buf.slice(0, n).toString("utf8").trim().toLowerCase();
  if (answer === "" || answer === "y" || answer === "yes") return { ok: true, answer };
  return { ok: false, reason: "declined", answer };
}
